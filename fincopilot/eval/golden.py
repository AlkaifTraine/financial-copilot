"""
Golden evaluation set.

Retrieval evaluation usually needs human relevance labels, which are expensive
and subjective. This set sidesteps that by asking questions whose answers are
**specific figures or named facts** that can be checked for automatically: if
the retrieved context contains "215,938", the retriever found the income
statement, and no judgement call was required.

Every expectation below was verified by hand against the filing it comes from.
That is the whole value of a golden set — if the expectations are themselves
generated by the system, the evaluation measures nothing.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class GoldenQuestion:
    """One question with automatically checkable expectations."""

    question: str

    # The retrieved context must contain at least one string from this list.
    # Alternatives cover formatting variation: "215,938" vs "215.9 billion".
    must_contain: list[str] = field(default_factory=list)

    # Optional: the section the answer should come from, for diagnosis.
    expect_section: str | None = None

    note: str = ""

    def matches(self, text: str) -> bool:
        haystack = text.lower().replace(",", "")
        return any(
            candidate.lower().replace(",", "") in haystack
            for candidate in self.must_contain
        )


